package com.urbanairship.automation.limits.storage

import androidx.room.Dao
import androidx.room.Insert
import androidx.room.OnConflictStrategy
import androidx.room.Query
import androidx.room.Transaction
import com.urbanairship.db.SuspendingBatchedQueryHelper.runBatched

/**
 * The maximum number of host parameters SQLite will bind in one statement.
 * See: https://sqlite.org/limits.html#max_variable_number
 */
private const val MAX_STATEMENT_PARAMETERS = 999

/**
 * An event row plus the shared group IDs it was recorded under, for a compound
 * insert. The event's `id` is generated by the insert, so a plain
 * [LedgerEventEntity] cannot carry its own [LedgerSharedIdEntity] rows ahead
 * of time.
 */
internal data class LedgerEventInsert(
    val entity: LedgerEventEntity,
    val sharedIds: List<String>
)

@Dao
internal interface LedgerDao {

    /**
     * Inserts raw [events] as a single unit, with no shared-group child rows.
     *
     * Used for events with no shared groups, and directly by tests to seed
     * rows [insertEvents] would not construct on its own (e.g. an
     * undecodable body).
     */
    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertAll(events: List<LedgerEventEntity>)

    /**
     * Inserts [events] as a single unit so a failure part way through leaves
     * no rows behind. Callers that retry a failed append rely on this: a
     * partial write would be re-appended on the next attempt and
     * double-count.
     *
     * Batched: one `@Insert` for every event entity, which returns the
     * generated row IDs in input order, then one `@Insert` for every
     * shared-group child row across all of them — two statements total
     * regardless of how many events are being written, rather than one pair
     * per event.
     */
    @Transaction
    suspend fun insertEvents(events: List<LedgerEventInsert>) {
        if (events.isEmpty()) {
            return
        }

        val eventIds = insertEventEntities(events.map { it.entity })
        // Paired by zip rather than by indexing `events` and `eventIds`
        // separately, so the two lists can't drift apart under a future edit
        // without it becoming a type error instead of a silent misattribution
        // of shared-group rows to the wrong event.
        val sharedIdRows = buildList {
            events.zip(eventIds).forEach { (insert, eventId) ->
                insert.sharedIds.forEach { add(LedgerSharedIdEntity(eventId = eventId, value = it)) }
            }
        }
        if (sharedIdRows.isNotEmpty()) {
            insertSharedIds(sharedIdRows)
        }
    }

    /** Returns the generated row ID of each inserted event, in input order. */
    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertEventEntities(events: List<LedgerEventEntity>): List<Long>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertSharedIds(rows: List<LedgerSharedIdEntity>)

    /**
     * Fetches the events recorded under [scheduleId] or any of [sharedIds],
     * oldest first. Ties on timestamp fall back to insert order.
     *
     * A shared ID matches an event two ways: against the event's own groups,
     * and against its `scheduleId`. The second is what lets a schedule naming
     * another schedule's ID as one of its groups pick up that schedule's
     * pre-existing history, which carries no groups of its own at all (e.g.
     * backfilled pre-ledger events).
     *
     * The group half is resolved as a subquery against
     * [LedgerSharedIdEntity]'s own indexed `value` column rather than a
     * three-way join, so it costs proportional to the matches rather than the
     * whole table. A zero-element [sharedIds] binds as `IN ()`, which SQLite
     * evaluates as always-false, so this already degenerates to exactly the
     * schedule's own events without a separate query for that case — which is
     * the narrowing a [LimitConfig.Self] schedule relies on.
     *
     * Past the SQL variable limit, [sharedIds] cannot be bound to one query —
     * unlike a delete, a fetch can't fall back to matching in Kotlin without
     * loading the whole table, so instead the schedule's own events and every
     * shared-group match are fetched in separate (batched) queries and merged,
     * de-duplicating by ID since an event can match more than one half.
     *
     * `@Transaction`, like every other multi-statement method in this file,
     * so a concurrent write can't be observed as a torn snapshot across the
     * batched sub-queries on the over-the-limit path. The common (single
     * query) path is naturally consistent on its own; the annotation costs it
     * nothing extra.
     */
    @Transaction
    suspend fun getEvents(scheduleId: String, sharedIds: List<String>): List<LedgerEventEntity> {
        // `sharedIds` appears twice in the query below, and Room expands each
        // occurrence into its own placeholder list, so the bound-parameter
        // count is two per ID plus the schedule's own.
        if (1 + 2 * sharedIds.size <= MAX_STATEMENT_PARAMETERS) {
            return getEventsByScheduleOrSharedIds(scheduleId, sharedIds)
        }

        val merged = LinkedHashMap<Long, LedgerEventEntity>()
        getEventsByScheduleOrSharedIds(scheduleId, emptyList()).forEach { merged[it.id] = it }
        // Half the statement limit per chunk, for the same reason as above:
        // the batched query binds each chunk once per axis it matches on.
        // `collectBatched` would chunk at the full limit and overflow.
        runBatched(MAX_STATEMENT_PARAMETERS / 2, sharedIds) { chunk ->
            getEventsBySharedIdsBatchInternal(chunk).forEach { merged[it.id] = it }
        }
        return merged.values.sortedWith(compareBy({ it.timestamp }, { it.id }))
    }

    @Query(
        "SELECT * FROM ledger_events " +
            "WHERE scheduleId = :scheduleId " +
            "OR scheduleId IN (:sharedIds) " +
            "OR id IN (SELECT eventId FROM ledger_shared_ids WHERE value IN (:sharedIds)) " +
            "ORDER BY timestamp ASC, id ASC"
    )
    suspend fun getEventsByScheduleOrSharedIds(
        scheduleId: String,
        sharedIds: List<String>
    ): List<LedgerEventEntity>

    /**
     * This query is only for internal use, by [getEvents]'s over-the-limit
     * fallback, with batched queries to avoid the max query params limit of
     * 999.
     *
     * Matches on both axes the single-query path does — an event's own groups
     * and its `scheduleId` — so an oversized group set still picks up a named
     * schedule's un-tagged history rather than silently losing it at the
     * threshold.
     */
    @Query(
        "SELECT * FROM ledger_events WHERE scheduleId IN (:sharedIds) " +
            "OR id IN (SELECT eventId FROM ledger_shared_ids WHERE value IN (:sharedIds))"
    )
    suspend fun getEventsBySharedIdsBatchInternal(sharedIds: Collection<String>): List<LedgerEventEntity>

    /**
     * True if any event is recorded under [scheduleId]. Answered from the
     * indexed column, so no body is decoded.
     */
    @Query("SELECT EXISTS(SELECT 1 FROM ledger_events WHERE scheduleId = :scheduleId)")
    suspend fun hasEvents(scheduleId: String): Boolean

    /**
     * The total number of stored rows, including rows whose body cannot be
     * decoded. Answered from the table, so no body is loaded.
     */
    @Query("SELECT COUNT(*) FROM ledger_events")
    suspend fun count(): Int

    /**
     * The smallest stored timestamp, or null when the ledger is empty. Answered
     * from the indexed column, so no body is loaded.
     */
    @Query("SELECT MIN(timestamp) FROM ledger_events")
    suspend fun oldestTimestamp(): Long?

    /** Every stored event, oldest first. Ties on timestamp fall back to insert order. */
    @Query("SELECT * FROM ledger_events ORDER BY timestamp ASC, id ASC")
    suspend fun getAllEvents(): List<LedgerEventEntity>

    /**
     * The recording scope of every stored row. Projects only the scope columns
     * (and each row's shared-group IDs), so retention can test rows for
     * orphanhood without loading any body.
     */
    @Transaction
    @Query("SELECT id, scheduleId FROM ledger_events")
    suspend fun getEventScopes(): List<LedgerEventScope>

    /**
     * Deletes every event orphaned on both axes: its recording schedule is in
     * neither [liveScheduleIds] nor [liveSharedIds] **and** none of its shared
     * groups, if it has any, is in [liveSharedIds]. A live shared ID names the
     * schedule whose history it inherits, so it keeps that schedule's events,
     * matching the `scheduleId IN (:sharedIds)` clause of
     * [getEventsByScheduleOrSharedIds].
     *
     * Picks its own strategy. While the bound IDs fit inside the statement
     * variable limit this is a single predicate delete that reads no rows.
     * Past that limit the predicate cannot be bound, and `NOT IN` cannot be
     * batched the way `IN` can — a chunk would delete the rows another chunk
     * keeps — so the orphans are identified from the scope columns instead and
     * deleted by primary key in batches. Either way the whole pass is one
     * transaction.
     *
     * @return the number of rows deleted.
     */
    @Transaction
    suspend fun deleteOrphanedEvents(
        liveScheduleIds: Set<String>,
        liveSharedIds: Set<String>
    ): Int {
        // The shared IDs are bound twice: against the schedule ID and against the group rows.
        if (liveScheduleIds.size + 2 * liveSharedIds.size <= MAX_STATEMENT_PARAMETERS) {
            return deleteOrphanedEventsInternal(liveScheduleIds, liveSharedIds)
        }

        val orphanIds = getEventScopes()
            .filter { scope ->
                scope.scheduleId !in liveScheduleIds &&
                        scope.scheduleId !in liveSharedIds &&
                        scope.sharedIds.none { it.value in liveSharedIds }
            }
            .map { it.id }

        var deleted = 0
        runBatched(orphanIds) { deleted += deleteByIdsBatchInternal(it) }
        return deleted
    }

    /**
     * Swaps the rows with the given primary keys for [events] as a single unit,
     * so a failure part way through can never leave the ledger holding the
     * pre-merge rows minus the ones already deleted. Rows outside [deleteIds]
     * are untouched, keeping their identity.
     */
    @Transaction
    suspend fun replaceEvents(deleteIds: List<Long>, events: List<LedgerEventInsert>) {
        runBatched(deleteIds) { deleteByIdsBatchInternal(it) }
        insertEvents(events)
    }

    @Transaction
    suspend fun deleteEvents(scheduleIds: List<String>, sharedIds: List<String>) {
        if (scheduleIds.isNotEmpty()) {
            runBatched(scheduleIds) { deleteByScheduleIdsBatchInternal(it) }
        }
        if (sharedIds.isNotEmpty()) {
            runBatched(sharedIds) { deleteBySharedIdsBatchInternal(it) }
        }
    }

    /**
     * This query is only for internal use, with batched queries
     * to avoid the max query params limit of 999.
     */
    @Query("DELETE FROM ledger_events WHERE scheduleId IN (:scheduleIds)")
    suspend fun deleteByScheduleIdsBatchInternal(scheduleIds: Collection<String>)

    /**
     * This query is only for internal use, with batched queries
     * to avoid the max query params limit of 999.
     *
     * Deletes by matching the shared-group rows on their own indexed `value`
     * column, then removing the events they point to. The child rows
     * themselves are taken with their events by the foreign key's cascade
     * rule, not by this statement.
     */
    @Query(
        "DELETE FROM ledger_events WHERE id IN (" +
            "SELECT eventId FROM ledger_shared_ids WHERE value IN (:sharedIds))"
    )
    suspend fun deleteBySharedIdsBatchInternal(sharedIds: Collection<String>)

    /**
     * This query is only for internal use, with batched queries
     * to avoid the max query params limit of 999.
     */
    @Query("DELETE FROM ledger_events WHERE id IN (:ids)")
    suspend fun deleteByIdsBatchInternal(ids: Collection<Long>): Int

    /**
     * This query is only for internal use, by [deleteOrphanedEvents], which
     * keeps the bound live IDs inside the statement variable limit.
     *
     * The shared-group half is a `NOT IN` subquery against the indexed
     * `value` column rather than a join, so a row with no shared groups at
     * all (whose subquery match is trivially empty) is judged on its
     * schedule alone. SQLite evaluates `x NOT IN ()` as true, so an empty
     * live-shared-IDs set correctly orphans everything on that axis.
     *
     * [liveSharedIds] is bound twice, against the schedule ID and against the
     * group rows, so the caller counts it twice toward the variable limit.
     */
    @Query(
        "DELETE FROM ledger_events " +
            "WHERE scheduleId NOT IN (:liveScheduleIds) " +
            "AND scheduleId NOT IN (:liveSharedIds) " +
            "AND id NOT IN (SELECT eventId FROM ledger_shared_ids WHERE value IN (:liveSharedIds))"
    )
    suspend fun deleteOrphanedEventsInternal(
        liveScheduleIds: Collection<String>,
        liveSharedIds: Collection<String>
    ): Int
}
